        function updatePageContent(lang) {
    const t = translations[lang] || translations.en;

    // NOTA: Os links do menu agora são gerenciados pelo WordPress
    // Não sobrescrever o conteúdo dos .nav-link para preservar o menu configurado no admin

    // Header Buttons
    const btnLogin = document.querySelector('.btn-login');
    const btnGetStarted = document.querySelector('.btn-get-started');

    if (btnLogin) btnLogin.textContent = t.login;
    if (btnGetStarted) btnGetStarted.textContent = t.getStarted;

    // Main Content
    const comingSoonTitle = document.querySelector('.coming-soon-title');
    const textParagraph = document.querySelector('.coming-soon-text');
    const btnHome = document.querySelector('.btn-home');

    if (comingSoonTitle) comingSoonTitle.textContent = t.comingSoon;
    if (textParagraph) textParagraph.innerHTML = t.unavailable + '<br>' + t.checkBack;
    if (btnHome) btnHome.textContent = t.home;

    // Footer
    const footerTitles = document.querySelectorAll('.footer-title');
    if (footerTitles.length >= 2) {
        footerTitles[0].textContent = t.membership;
        footerTitles[1].textContent = t.resources;
    }

    const footerLinks = document.querySelectorAll('.footer-links a');
    if (footerLinks.length >= 6) {
        footerLinks[0].textContent = t.howItWorks;
        footerLinks[1].textContent = t.membershipPlans;
        footerLinks[2].textContent = t.sponsorship;
        footerLinks[3].textContent = t.discordCommunity;
        footerLinks[4].textContent = t.contactSupport;
        footerLinks[5].textContent = t.challenges2;
    }

    const copyrightEl = document.querySelector('.copyright');
    if (copyrightEl) copyrightEl.textContent = t.copyright;

    const footerLegalLinks = document.querySelectorAll('.footer-legal a');
    if (footerLegalLinks.length >= 2) {
        footerLegalLinks[0].textContent = t.privacy;
        footerLegalLinks[1].textContent = t.terms;
    }

    const subscribeInput = document.querySelector('.subscribe-input');
    if (subscribeInput) subscribeInput.placeholder = t.subscribe;

    // About dropdown translations
    const aboutDropdownItems = document.querySelectorAll('#aboutDropdown .nav-dropdown-item');
    aboutDropdownItems.forEach(item => {
        const key = item.getAttribute('data-i18n');
        if (key && t[key]) {
            item.textContent = t[key];
        }
    });

    // Modal translations
    const modalTitle = document.getElementById('modalTitle');
    const modalSubtitle = document.getElementById('modalSubtitle');
    const loginTab = document.getElementById('loginTab');
    const signupTab = document.getElementById('signupTab');

    if (modalTitle) {
        const isSignUp = signupTab && signupTab.classList.contains('active');
        modalTitle.textContent = isSignUp ? t.modalSignUp : t.modalWelcome;
    }

    if (modalSubtitle) modalSubtitle.textContent = t.modalSubtitle;

    if (loginTab) loginTab.textContent = t.modalLoginTab;
    if (signupTab) signupTab.textContent = t.modalSignUpTab;

    // Input placeholders
    const loginEmail = document.getElementById('loginEmail');
    const signupEmail = document.getElementById('signupEmail');
    const loginPassword = document.getElementById('loginPassword');
    const signupPassword = document.getElementById('signupPassword');

    if (loginEmail) loginEmail.placeholder = t.modalEmail;
    if (signupEmail) signupEmail.placeholder = t.modalEmail;
    if (loginPassword) loginPassword.placeholder = t.modalPassword;
    if (signupPassword) signupPassword.placeholder = t.modalPassword;

    // Forgot password
    const forgotPassword = document.querySelector('.forgot-password');
    if (forgotPassword) forgotPassword.textContent = t.modalForgotPassword;

    // Continue buttons
    const continueButtons = document.querySelectorAll('.btn-continue');
    continueButtons.forEach(btn => {
        if (btn.id !== 'sendEmailBtn') {
            btn.textContent = t.modalContinue;
        }
    });

    // Send email button
    const sendEmailBtn = document.getElementById('sendEmailBtn');
    if (sendEmailBtn) sendEmailBtn.textContent = t.modalSendEmail;

    // Divider
    document.querySelectorAll('.divider span')
        .forEach(span => span.textContent = t.modalOr);

    // Google button
    document.querySelectorAll('.btn-google')
        .forEach(btn => {
            btn.innerHTML = '<i class="fab fa-google"></i> ' + t.modalGoogleContinue;
        });

    // Password requirements
    const requirementsTitle = document.querySelector('.requirements-title');
    if (requirementsTitle) requirementsTitle.textContent = t.modalPasswordRequirements;

    const uppercaseReq = document.querySelector('#uppercaseReq span');
    if (uppercaseReq) uppercaseReq.textContent = t.modalUppercase;

    const lengthReq = document.querySelector('#lengthReq span');
    if (lengthReq) lengthReq.textContent = t.modalCharacters;

    // Terms text
    const termsText = document.querySelector('.terms-text');
    if (termsText) {
        const termsLinks = termsText.querySelectorAll('a');
        termsText.childNodes[0].textContent = t.modalTermsText + ' ';
        if (termsLinks[0]) termsLinks[0].textContent = t.modalTermsUse;
        if (termsLinks[1]) termsLinks[1].textContent = t.modalPrivacyPolicy;
    }
}

        
        function toggleMobileMenu() {
            const navMenu = document.getElementById('navMenu');
            const menuIcon = document.querySelector('.mobile-menu-toggle i');
            
            // Fechar dropdowns de idioma quando abrir o menu
            const dropdownDesktop = document.getElementById('languageDropdown');
            const dropdownMobile = document.getElementById('languageDropdownMobile');
            if (dropdownDesktop) dropdownDesktop.classList.remove('active');
            if (dropdownMobile) dropdownMobile.classList.remove('active');
            
            navMenu.classList.toggle('active');
            
            // Alternar entre ícone de menu (bars) e X (times)
            if (menuIcon) {
                if (navMenu.classList.contains('active')) {
                    menuIcon.classList.remove('fa-bars');
                    menuIcon.classList.add('fa-times');
                } else {
                    menuIcon.classList.remove('fa-times');
                    menuIcon.classList.add('fa-bars');
                }
            }
        }
        
        function toggleLanguageMenu(event) {
            event.stopPropagation();
            
            const dropdownDesktop = document.getElementById('languageDropdown');
            const dropdownMobile = document.getElementById('languageDropdownMobile');
            
            // Fechar menu mobile se estiver aberto
            const navMenu = document.getElementById('navMenu');
            if (navMenu) navMenu.classList.remove('active');
            
            // Fechar dropdowns de navegação
            document.querySelectorAll('.nav-dropdown-menu').forEach(menu => {
                menu.classList.remove('active');
            });
            
            // Toggle ambos os dropdowns
            if (dropdownDesktop) dropdownDesktop.classList.toggle('active');
            if (dropdownMobile) dropdownMobile.classList.toggle('active');
        }
        
        // Toggle Navigation Dropdown
        function toggleNavDropdown(event, dropdownId) {
            event.preventDefault();
            event.stopPropagation();
            
            const dropdown = document.getElementById(dropdownId);
            const allDropdowns = document.querySelectorAll('.nav-dropdown-menu');
            
            // Fechar dropdowns de idioma
            const dropdownDesktop = document.getElementById('languageDropdown');
            const dropdownMobile = document.getElementById('languageDropdownMobile');
            if (dropdownDesktop) dropdownDesktop.classList.remove('active');
            if (dropdownMobile) dropdownMobile.classList.remove('active');
            
            // Fechar outros dropdowns
            allDropdowns.forEach(menu => {
                if (menu.id !== dropdownId) {
                    menu.classList.remove('active');
                }
            });
            
            // Toggle o dropdown clicado
            dropdown.classList.toggle('active');
        }
        
        // Fechar dropdowns ao clicar fora
        document.addEventListener('click', (event) => {
            // Fechar dropdowns de navegação
            if (!event.target.closest('.nav-dropdown')) {
                document.querySelectorAll('.nav-dropdown-menu').forEach(menu => {
                    menu.classList.remove('active');
                });
            }
            
            // Fechar dropdowns de idioma
            if (!event.target.closest('.language-selector')) {
                const dropdownDesktop = document.getElementById('languageDropdown');
                const dropdownMobile = document.getElementById('languageDropdownMobile');
                if (dropdownDesktop) dropdownDesktop.classList.remove('active');
                if (dropdownMobile) dropdownMobile.classList.remove('active');
            }
        });
        
        function changeLanguage(lang, country, event) {
            event.stopPropagation();
            
            // Atualizar bandeiras (desktop e mobile)
            const currentFlag = document.getElementById('currentFlag');
            const currentFlagMobile = document.getElementById('currentFlagMobile');
            
            if (currentFlag) {
                currentFlag.src = `https://flagcdn.com/w40/${country}.png`;
                currentFlag.alt = lang.toUpperCase();
            }
            
            if (currentFlagMobile) {
                currentFlagMobile.src = `https://flagcdn.com/w40/${country}.png`;
                currentFlagMobile.alt = lang.toUpperCase();
            }
            
            // Salvar preferência no localStorage
            localStorage.setItem('selectedLanguage', lang);
            localStorage.setItem('selectedCountry', country);
            
            // Fechar dropdowns
            const dropdowns = document.querySelectorAll('.language-dropdown');
            dropdowns.forEach(dropdown => dropdown.classList.remove('active'));
            
            // Atualizar atributo lang do HTML
            document.documentElement.lang = lang;
            
            // Atualizar conteúdo da página
            updatePageContent(lang);
        }
        
        // Carregar idioma salvo ao carregar a página
        window.addEventListener('DOMContentLoaded', () => {
            const savedLang = localStorage.getItem('selectedLanguage');
            const savedCountry = localStorage.getItem('selectedCountry');
            
            if (savedLang && savedCountry) {
                const currentFlag = document.getElementById('currentFlag');
                currentFlag.src = `https://flagcdn.com/w40/${savedCountry}.png`;
                currentFlag.alt = savedLang.toUpperCase();
                document.documentElement.lang = savedLang;
                updatePageContent(savedLang);
            } else {
                // Carregar idioma padrão (inglês)
                updatePageContent('en');
            }
        });
        
        // Fechar menu mobile apenas em links sem dropdown
        document.querySelectorAll('.nav-link').forEach(link => {
            link.addEventListener('click', (e) => {
                // Não fechar se for um link com dropdown
                const parentDropdown = link.closest('.nav-dropdown');
                if (!parentDropdown) {
                    // Só fecha o menu se não for um dropdown
                    document.getElementById('navMenu').classList.remove('active');
                }
            });
        });
        
        // Fechar menu mobile ao clicar em itens do dropdown
        document.querySelectorAll('.nav-dropdown-item').forEach(item => {
            item.addEventListener('click', () => {
                document.getElementById('navMenu').classList.remove('active');
            });
        });
        
        // Fechar dropdowns ao clicar fora
        document.addEventListener('click', (event) => {
            if (!event.target.closest('.language-selector')) {
                document.getElementById('languageDropdown').classList.remove('active');
            }
        });
        
        