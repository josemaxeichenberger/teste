function switchAccountTab(tabName) {
    // Remover classe active de todas as abas
    const tabs = document.querySelectorAll('.account-tab');
    tabs.forEach(tab => tab.classList.remove('active'));
    
    // Adicionar classe active na aba clicada
    if (event && event.target) {
        event.target.classList.add('active');
    } else {
        // Se chamado programaticamente, encontrar o botão correto
        // Encontrar e ativar o botão correto baseado no nome da tab
tabs.forEach(tab => {
    if (tab.textContent.toLowerCase().trim() === tabName.toLowerCase()) {
        tab.classList.add('active');
    }
});
    }
    
    // Esconder todo o conteúdo
    const tabContents = document.querySelectorAll('.tab-content');
    tabContents.forEach(content => content.classList.remove('active'));
    
    // Mostrar o conteúdo correspondente
    if (tabName === 'challenges') {
        document.getElementById('challengesTab').classList.add('active');
    } else if (tabName === 'affiliation') {
        document.getElementById('affiliationTab').classList.add('active');
    } else if (tabName === 'settings') {
        document.getElementById('settingsTab').classList.add('active');
    } else if (tabName === 'billing') {
        // Adicionar billing quando existir
        const billingTab = document.getElementById('billingTab');
        if (billingTab) billingTab.classList.add('active');
    }
    
    // Atualizar URL sem recarregar a página
    const url = new URL(window.location);
    url.searchParams.set('tab', tabName);
    window.history.pushState({tab: tabName}, '', url);
}

// Verificar parâmetro da URL ao carregar a página
// O PHP já define as classes 'active' corretamente, então só precisamos
// garantir que o JavaScript não sobrescreva se já estiver correto
const urlParams = new URLSearchParams(window.location.search);
const tabParam = urlParams.get('tab');

// Só chamar switchAccountTab se houver um parâmetro e a tab ainda não estiver ativa
if (tabParam && ['challenges', 'billing', 'affiliation', 'settings'].includes(tabParam)) {
    const currentActiveTab = document.querySelector('.account-tab.active');
    const currentTabName = currentActiveTab ? currentActiveTab.textContent.toLowerCase().trim() : '';
    
    // Só troca se a tab ativa não for a mesma do parâmetro
    if (currentTabName !== tabParam) {
        switchAccountTab(tabParam);
    }
}

// Lidar com navegação do histórico (botão voltar/avançar do navegador)
window.addEventListener('popstate', function(event) {
    if (event.state && event.state.tab) {
        switchAccountTab(event.state.tab);
    } else {
        const urlParams = new URLSearchParams(window.location.search);
        const tabParam = urlParams.get('tab') || 'challenges';
        switchAccountTab(tabParam);
    }
});




