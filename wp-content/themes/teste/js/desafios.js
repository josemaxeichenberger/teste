/**
 * Event listener para input de código (auto-submit)
 */
document.addEventListener('DOMContentLoaded', function() {
    const codeInput = document.getElementById('verificationCodeInput');
    
    if (codeInput) {
        codeInput.addEventListener('input', function() {
            // Permitir apenas números
            this.value = this.value.replace(/\D/g, '');
            
            // Limitar a 4 dígitos
            if (this.value.length > 4) {
                this.value = this.value.substring(0, 4);
            }
            
            // Auto-submit quando completar 4 dígitos (com pequeno delay)
            if (this.value.length === 4) {
                setTimeout(() => {
                    verifyPhoneCode(this.value);
                }, 300);
            }
        });
    }
    
    // Event listener para o botão de reenviar
    const resendBtn = document.getElementById('resendBtnModal');
    if (resendBtn) {
        resendBtn.addEventListener('click', resendPhoneCode);
    }
});

/**
 * Verificar código de verificação
 */
function verifyPhoneCode(code) {
    const codeInput = document.getElementById('verificationCodeInput');
    
    // Evitar múltiplas chamadas
    if (codeInput.disabled) {
        return;
    }
    
    codeInput.disabled = true;
    
    const language = localStorage.getItem('selectedLanguage') || 'pt';
    
    fetch(apiBaseUrl + 'verify-phone-change.php', {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json'
        },
        body: JSON.stringify({
            code: code,
            language: language
        })
    })
    .then(response => response.json())
    .then(data => {
        if (data.success) {
            // Sucesso! Telefone atualizado
            showMessage(data.message, 'success');
            
            // Atualizar telefone exibido na página
            const phoneDisplay = document.getElementById('phoneDisplay');
            if (phoneDisplay) {
                phoneDisplay.textContent = data.newPhone;
            }
            
            // Fechar modal após 1.5 segundos
            setTimeout(() => {
                closePhoneModal();
                
                // Recarregar página para atualizar dados
                window.location.reload();
            }, 1500);
            
        } else {
            // Erro na verificação
            codeInput.disabled = false;
            codeInput.value = '';
            codeInput.focus();
            
            // Mensagens específicas por tipo de erro
            let errorMessage = data.message;
            
            if (data.error_code === 'CODE_EXPIRED') {
                errorMessage += '\n\n⏱️ Solicite um novo código clicando em "Reenviar código".';
            } else if (data.error_code === 'MAX_ATTEMPTS') {
                errorMessage += '\n\n🔒 Por segurança, você precisará solicitar um novo código.';
                // Voltar para Step 1
                setTimeout(() => {
                    backToPhoneInput();
                }, 2000);
            }
            
            showMessage(errorMessage, 'error');
        }
    })
    .catch(error => {
        console.error('Erro ao verificar código:', error);
        codeInput.disabled = false;
        codeInput.value = '';
        codeInput.focus();
        showMessage('Erro ao processar verificação. Tente novamente.', 'error');
    });
}

