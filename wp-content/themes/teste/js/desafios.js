/**
 * Iniciar timer de reenvio de código
 */
function startPhoneResendTimer(seconds = 180) {
    const resendBtn = document.getElementById('resendBtnModal');
    let timeLeft = seconds;
    
    resendBtn.disabled = true;
    
    // Limpar timer anterior se existir
    if (phoneChangeTimer) {
        clearInterval(phoneChangeTimer);
    }
    
    phoneChangeTimer = setInterval(() => {
        timeLeft--;
        
        if (timeLeft > 0) {
            const minutes = Math.floor(timeLeft / 60);
            const secs = timeLeft % 60;
            resendBtn.innerHTML = `Reenviar em ${minutes}:${secs.toString().padStart(2, '0')}`;
        } else {
            clearInterval(phoneChangeTimer);
            resendBtn.disabled = false;
            resendBtn.innerHTML = 'Reenviar código';
        }
    }, 1000);
}

